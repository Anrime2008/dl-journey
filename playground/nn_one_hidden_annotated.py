# 固定随机种子。神经网络初始化权重是"随机"的，固定种子后每次跑结果一样，
# 方便对比。seed(1) 里的 1 就是种子编号，改成别的数结果会变。
np.random.seed(1)


# =============================================================================
# 第 1 步：造数据
# =============================================================================
# def 是"定义一个函数"，相当于 C++ 里的 返回类型 函数名(参数)。
# 这里函数名叫 load_data，括号里的 m=400 是"默认参数"：
# 调用时不写就用 400，写 load_data(1000) 就用 1000。
def load_data(m=400):
    # 下面三行双引号包起来的东西叫"文档字符串"（docstring），
    # 它不影响运行，纯粹是给读代码的人看的说明。Ctrl+鼠标悬停能看到。
    """
    造一个"同心圆"数据集：里面一圈是类别 0，外面一圈是类别 1。
    这种数据用一条直线分不开，必须靠隐藏层。

    返回：
        X: 形状 (2, m)，每一列是一个点的坐标（x1, x2）
        Y: 形状 (1, m)，每一列是标签（0 或 1）
    """

    # np.random.rand(m)：生成 m 个 0~1 之间的随机小数，返回一个长度为 m 的数组。
    theta = np.random.rand(m) * 2 * np.pi
    # 上面这行：乘以 2π，就变成 0~2π 的随机角度（相当于随便挑一个方向）。
    # np.pi 就是圆周率 π。

    # 再随机一个半径。先取 0~1 的随机数，开根号，再乘 3。
    # 为什么要开根号：直接取 r 的话，点会挤在圆心；开根号能让点在圆面上均匀分布。
    r = np.sqrt(np.random.rand(m)) * 3

    # cos/sin 把"角度 + 半径"换算成 x、y 坐标。
    x1 = r * np.cos(theta)
    x2 = r * np.sin(theta)

    # np.vstack((a, b))：把两个数组上下叠起来，变成两行。
    # 结果 X 的形状是 (2, m)：第 0 行是所有 x1，第 1 行是所有 x2。
    X = np.vstack((x1, x2))

    # (r > 1.5)：对数组里每个元素判断"半径是否大于 1.5"，得到一堆 True/False。
    # .astype(float)：把 True/False 变成 1.0/0.0。
    # .reshape(1, m)：把形状从 (m,) 变成 (1, m)，变成"一行 m 列"，和 X 对齐。
    Y = (r > 1.5).astype(float).reshape(1, m)

    # return 就是"把这两个东西交出去"，调用者会拿到 X 和 Y。
    return X, Y


# =============================================================================
# 第 2 步：初始化参数（W 和 b）
# =============================================================================
def initialize_parameters(n_x, n_h, n_y):
    """
    n_x = 输入有几个特征（这里是 2：x1 和 x2）
    n_h = 隐藏层有几个神经元（这里是 8）
    n_y = 输出几个（这里是 1：是不是外圈）

    神经网络要学的东西就是这些 W 和 b。一开始没有，得先随便给个值。
    """

    # np.random.randn(n_h, n_x)：生成 n_h 行 n_x 列的随机数，
    # 每个数服从标准正态分布（有正有负，大部分在 -2~2 之间）。
    # 为什么乘 0.01：让初始值很小。如果 W 太大，第一层的输出会很大，
    # tanh 会跑到"两头很平"的区域，那里梯度接近 0，网络就学不动了。
    W1 = np.random.randn(n_h, n_x) * 0.01

    # np.zeros((n_h, 1))：生成 n_h 行 1 列的全 0 数组。
    # 注意括号：((n_h, 1)) 里那一层小括号是"形状元组"，不能少。
    b1 = np.zeros((n_h, 1))

    # 第二层的权重：n_y 行 n_h 列。它的输入是第一层的 8 个输出。
    W2 = np.random.randn(n_y, n_h) * 0.01

    # 第二层的偏置：n_y 行 1 列。
    b2 = np.zeros((n_y, 1))

    # assert 是"断言"：我确信括号里的条件成立，不成立就立刻报错停下。
    # .shape 是数组的形状，比如 (8, 2) 表示 8 行 2 列。
    # 这样写是在给自己留检查点——形状错了会算出一堆莫名其妙的数，还不报错。
    assert W1.shape == (n_h, n_x)
    assert b1.shape == (n_h, 1)
    assert W2.shape == (n_y, n_h)
    assert b2.shape == (n_y, 1)

    # 把四个东西装进一个"字典"（dict）里一起返回。
    # 字典就是"键 → 值"的表格，相当于 C++ 的 map<string, 矩阵>。
    # 后面用 params["W1"] 就能把 W1 取出来。
    return {"W1": W1, "b1": b1, "W2": W2, "b2": b2}


# =============================================================================
# 第 3 步：前向传播（从输入一路算到预测值）
# =============================================================================
def forward_propagation(X, params):
    """
    输入：
        X      形状 (n_x, m)
        params 上一步返回的字典

    做四件事（这就是整个网络的"前向"）：
        Z1 = W1·X + b1     第一层：把输入线性组合
        A1 = tanh(Z1)      第一层激活：把数压到 -1~1
        Z2 = W2·A1 + b2    第二层：把第一层的输出再组合
        A2 = sigmoid(Z2)   第二层激活：压到 0~1，当概率用
    """

    # 从字典里把四个参数取出来。左边四个变量 = 右边的四个值，这叫"解包"。
    W1, b1, W2, b2 = params["W1"], params["b1"], params["W2"], params["b2"]

    # @ 是矩阵乘法（等价于 np.dot）。注意不是 *，* 是"对应位置相乘"，完全不同！
    # W1 是 (8,2)，X 是 (2,m)，矩阵乘法结果 Z1 是 (8,m)。
    # + b1：numpy 会自动把 (8,1) 的 b1 "广播"到每一列上（自动补形状），
    # 相当于给这 8 行每一行都加上同一个 b1。
    Z1 = W1 @ X + b1

    # np.tanh 是双曲正切函数，把任意大的数压到 -1~1 之间。
    # 它是"激活函数"，作用：如果不用它，两层线性运算叠起来还是线性的，
    # 等于白搭一层。用了它，网络才有能力拟合"弯的"边界。
    A1 = np.tanh(Z1)

    # 第二层同样的套路：W2 是 (1,8)，A1 是 (8,m)，乘完 Z2 是 (1,m)。
    Z2 = W2 @ A1 + b2

    # sigmoid 公式：1 / (1 + e^(-z))。自己写公式而不用库函数，
    # 是为了让你看见它就是"把任意数压到 0~1"。
    # np.exp(-Z2) 会对 Z2 里每个元素单独算 e 的 -Z2 次方。
    A2 = 1 / (1 + np.exp(-Z2))

    # 再检查一次形状：A2 应该是 (1, m)，和样本数一致。
    assert A2.shape == (1, X.shape[1])

    # cache 是"缓存"：把中间结果存起来，反向传播要用。
    # 不存的话，反向时得把前向再算一遍，浪费。
    cache = {"Z1": Z1, "A1": A1, "Z2": Z2, "A2": A2}

    # 返回预测值 A2，以及缓存。
    return A2, cache


# =============================================================================
# 第 4 步：算代价（预测得有多差）
# =============================================================================
def compute_cost(A2, Y):
    """
    交叉熵公式：J = -(1/m) * Σ[ y·log(â) + (1-y)·log(1-â) ]
    一句话理解：猜错得越离谱，这个数越大；猜对了，它接近 0。
    """

    # Y.shape 是 (1, m)，取第 1 个元素就是 m（样本数）。
    m = Y.shape[1]

    # 这一行是公式的代码版，拆开看：
    #   Y * np.log(A2 + 1e-8)          真值是 1 的那些样本，算 log(预测概率)
    #   (1 - Y) * np.log(1 - A2 + 1e-8) 真值是 0 的那些样本，算 log(1-预测概率)
    #   两者相加再 np.sum，就是所有样本加起来
    #   / m 求平均，前面加负号把"负数"变正数
    # 为什么加 1e-8：如果预测正好是 0 或 1，log(0) 会变成负无穷，程序会崩。
    # 加个极小值防止这种情况，这是数值稳定的常见小技巧。
    cost = -np.sum(Y * np.log(A2 + 1e-8) + (1 - Y) * np.log(1 - A2 + 1e-8)) / m

    # np.squeeze 把形状是 (1,1) 的数组压成普通数字（去掉多余的维度）。
    # float(...) 保证返回的是普通小数，而不是 numpy 的数组。
    return float(np.squeeze(cost))


# =============================================================================
# 第 5 步：反向传播（算出每个参数该往哪个方向改）
# =============================================================================
def backward_propagation(params, cache, X, Y):
    """
    这是整个神经网络最核心的一段。六个公式，全部来自链式法则。

    直观理解：
        先算"输出层错了多少"（dZ2）
        → 由此算出 W2、b2 该改多少
        → 再把这个错误"按权重比例"传回隐藏层（dZ1）
        → 由此算出 W1、b1 该改多少
    """

    # 样本数，后面每条梯度都要除以它。
    m = X.shape[1]

    # 从字典里取出需要的中间结果。
    W2 = params["W2"]           # (1, 8)
    A1 = cache["A1"]            # (8, m)，第一层的输出
    A2 = cache["A2"]            # (1, m)，最终预测值

    # ① 输出层的误差：预测值减真值。
    # 为什么这么简单？因为交叉熵 + sigmoid 求导之后，刚好化简成 A2 - Y。
    dZ2 = A2 - Y                                    # 形状 (1, m)

    # ② W2 的梯度 = dZ2 乘 A1 的转置，再除以 m。
    # .T 是转置：(8,m) 转成 (m,8)，这样 (1,m)@(m,8) 才能乘出 (1,8)，和 W2 同形状。
    # 除以 m 是因为代价是平均值，对平均值求导要除 m。
    dW2 = dZ2 @ A1.T / m                            # 形状 (1, 8)

    # ③ b2 的梯度 = 把 dZ2 按行加起来（axis=1 表示"沿列方向求和"，把 m 个样本汇总）。
    # keepdims=True 是为了保持 (1,1) 的形状，而不是变成标量。
    db2 = np.sum(dZ2, axis=1, keepdims=True) / m    # 形状 (1, 1)

    # ④ 把误差传回隐藏层。
    # W2.T @ dZ2：把输出层的误差按 W2 的比例"分"回 8 个神经元，得到 (8, m)。
    # (1 - A1 ** 2)：tanh 的导数正好等于 1 - tanh²，而 A1 就是 tanh(Z1)。
    #   ** 是幂运算，A1 ** 2 就是 A1 的平方。
    # 两个一乘，就是隐藏层的误差 dZ1。
    dZ1 = (W2.T @ dZ2) * (1 - A1 ** 2)              # 形状 (8, m)

    # ⑤ W1 的梯度：dZ1 乘 X 的转置，再除 m。
    # X.T 是 (m,2)，(8,m)@(m,2) 得到 (8,2)，和 W1 同形状。
    dW1 = dZ1 @ X.T / m                             # 形状 (8, 2)

    # ⑥ b1 的梯度：同 ③，按行求和。
    db1 = np.sum(dZ1, axis=1, keepdims=True) / m    # 形状 (8, 1)

    # 检查形状，防止算错还不自知。
    assert dW1.shape == params["W1"].shape
    assert dW2.shape == params["W2"].shape

    # 六个梯度打包返回。
    return {"dW1": dW1, "db1": db1, "dW2": dW2, "db2": db2}


# =============================================================================
# 第 6 步：梯度下降（真的去改参数）
# =============================================================================
def update_parameters(params, grads, learning_rate):
    """
    公式就一句：参数 = 参数 - 学习率 × 梯度
    为什么是减：梯度指向"上坡"（代价变大的方向），减掉它就是往下坡走。
    """

    # -= 是"减完再赋值给自己"，等价于 W1 = W1 - learning_rate * dW1。
    # 这样写省事，也不用临时变量。
    params["W1"] -= learning_rate * grads["dW1"]
    params["b1"] -= learning_rate * grads["db1"]
    params["W2"] -= learning_rate * grads["dW2"]
    params["b2"] -= learning_rate * grads["db2"]

    # 参数是字典，直接改了字典里的值，再返回出去（其实原地改也行，写出来更清楚）。
    return params


# =============================================================================
# 第 7 步：把前面几步串起来，反复训练
# =============================================================================
def nn_model(X, Y, n_h=8, num_iterations=10000, learning_rate=1.0):
    """
    每一轮做的四件事（顺序永远是这个，背下来）：
        前向 → 算代价 → 反向 → 更新
    重复 num_iterations 次。
    """

    # X.shape 是 (2, m)，取第 0 个元素就是输入维度 n_x = 2。
    n_x = X.shape[0]
    # 同理，输出维度 n_y = 1。
    n_y = Y.shape[0]

    # 第一步：初始化参数。
    params = initialize_parameters(n_x, n_h, n_y)

    # 空列表，用来存每一轮的代价，最后画曲线用。
    costs = []

    # for i in range(n)：让 i 从 0 数到 n-1，循环 n 次。
    # 这是 Python 最常用的循环写法，相当于 C++ 的 for (int i = 0; i < n; i++)。
    for i in range(num_iterations):
        # ① 前向：用当前参数算出预测值，同时拿到中间结果（cache）。
        A2, cache = forward_propagation(X, params)

        # ② 算代价：看当前预测有多差。
        cost = compute_cost(A2, Y)

        # ③ 反向：算出每个参数该往哪改、改多少。
        grads = backward_propagation(params, cache, X, Y)

        # ④ 更新：真的改一下参数。
        params = update_parameters(params, grads, learning_rate)

        # i % 2000 == 0：i 除以 2000 的余数为 0，也就是 0、2000、4000…… 这些轮。
        # 每 2000 轮打印一次，不用每轮都打（不然屏幕刷太快）。
        if i % 2000 == 0:
            # f"..." 叫 f-string：字符串前面加 f，里面 {cost:.6f} 会被替换成变量的值。
            # :.6f 意思是"保留 6 位小数，按浮点数格式输出"。
            # {i:5d} 意思是"占 5 个字符宽度，整数格式"，让数字对齐好看。
            print(f"第 {i:5d} 轮   cost = {cost:.6f}")

        # .append 是往列表末尾追加一个元素。
        costs.append(cost)

    # 训练完，把最终参数和代价历史都返回。
    return params, costs


# =============================================================================
# 第 8 步：用训练好的参数做预测
# =============================================================================
def predict(params, X):
    """
    把数据送进网络，得到概率；概率大于 0.5 就判为 1，否则判为 0。
    """

    # 只要预测值，不要 cache，所以第二个返回值用 _ 接住（下划线表示"我不要"）。
    A2, _ = forward_propagation(X, params)

    # A2 > 0.5 会对每个元素判断，得到一个 True/False 的数组。
    # .astype(int) 把 True/False 变成 1/0。
    return (A2 > 0.5).astype(int)


# =============================================================================
# 主程序：把上面所有东西真的跑一遍
# =============================================================================
def main():
    # 造 400 个点。
    X, Y = load_data(400)

    # 打印形状，确认数据没问题。
    print("数据形状 X:", X.shape, " Y:", Y.shape, "\n")

    # 训练：隐藏层 8 个神经元，迭代 10000 轮，学习率 1.0。
    params, costs = nn_model(X, Y, n_h=8, num_iterations=10000, learning_rate=1.0)

    # 用训练好的参数在训练集上预测。
    pred = predict(params, X)

    # np.mean 求平均：pred == Y 会得到一堆 True/False，
    # 求平均就是"猜对的比例"，乘 100 变成百分比。
    acc = np.mean(pred == Y) * 100
    print(f"\n训练集准确率：{acc:.2f}%")

    # ---------------- 画决策边界 ----------------
    # np.linspace(-3.2, 3.2, 300)：在 -3.2 到 3.2 之间均匀取 300 个数。
    # np.meshgrid 把两个一维数组变成二维网格（x 坐标表、y 坐标表）。
    xx, yy = np.meshgrid(np.linspace(-3.2, 3.2, 300), np.linspace(-3.2, 3.2, 300))

    # .ravel() 把二维表格拉平成一维长条。
    # np.vstack 再把它叠成 (2, 90000)，这样就能整批送进网络。
    grid = np.vstack((xx.ravel(), yy.ravel()))

    # 对这 9 万个点做预测，再 .reshape 回 300×300 的表格，方便画图。
    Z = predict(params, grid).reshape(xx.shape)

    # 开一张 6×5 英寸的图。
    plt.figure(figsize=(6, 5))

    # contourf 画"填充的等高线"，也就是把预测为 0 和 1 的区域涂成两种颜色。
    # alpha=0.25 是半透明，不然会把点盖住。
    plt.contourf(xx, yy, Z, alpha=0.25, cmap="RdBu")

    # 把真实数据点画上去：先画类别 0（内圈），再画类别 1（外圈）。
    # X[0, Y[0] == 0] 的意思是"取所有标签为 0 的点的 x1 坐标"。
    plt.scatter(X[0, Y[0] == 0], X[1, Y[0] == 0], s=12, c="#2f4a5c", label="class 0")
    plt.scatter(X[0, Y[0] == 1], X[1, Y[0] == 1], s=12, c="#a8342a", label="class 1")

    # 显示图例（右上角那个小标签）。
    plt.legend(loc="upper right", fontsize=9)

    # 标题。
    plt.title(f"1 hidden layer (n_h=8), acc={acc:.1f}%")

    # 自动调整边距，避免标签被切掉。
    plt.tight_layout()

    # 存图。os.path.join 用来拼路径，保证存到脚本所在文件夹。
    plt.savefig(os.path.join(HERE, "nn_boundary.png"), dpi=130)
