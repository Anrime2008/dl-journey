# 12 矩阵乘法
# ============================================================
A = [[1, 2, 3],
     [4, 5, 6]]
B = [[7, 8],
     [9, 10],
     [11, 12]]

# A 是 2x3，B 是 3x2，结果 C 是 2x2
C = []                                   # 先造一个空的结果表
for i in range(len(A)):                  # 结果的行数 = A 的行数
    row = []                             # 先准备这一行
    for j in range(len(B[0])):           # 结果的列数 = B 的列数
        s = 0
        for k in range(len(B)):          # 内维长度 3，逐个乘加
            s += A[i][k] * B[k][j]
        row.append(s)                    # 把这个数塞进这一行
    C.append(row)                        # 这一行塞进结果表

for row in C:
    print(row)                           # [58, 64] / [139, 154]

